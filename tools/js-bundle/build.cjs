const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');

const root = path.resolve(__dirname, '../..');
const sourceRoot = 'web/src/js';
const groups = ['components', 'pages'];

// The static area each bundle ships in. The public host only serves shared and public, and the
// panel serves admin only to signed-in users, so a bundle's area decides who can download it.
const AREAS = {
  telemetry: 'shared',
  chart: 'shared',
  admin_core: 'admin',
  network_monitors: 'admin',
  admin_agents: 'admin',
  public_dashboard: 'public'
};

// Every web/src/js/{components,pages}/<name>/index.js is one bundle, built to
// web/static/<area>/js/<name>.js; the files under it are grouped into concern folders and combined here.
function entries() {
  const found = [];
  for (const group of groups) {
    const dir = path.join(root, sourceRoot, group);
    if (!fs.existsSync(dir)) continue;
    for (const item of fs.readdirSync(dir, {withFileTypes: true})) {
      if (item.isDirectory() && fs.existsSync(path.join(dir, item.name, 'index.js'))) {
        found.push({name: item.name, source: sourceRoot + '/' + group + '/' + item.name});
      }
    }
  }
  found.sort((a, b) => a.name.localeCompare(b.name));
  const seen = new Set();
  for (const entry of found) {
    if (seen.has(entry.name)) throw new Error('Two bundles are named ' + entry.name);
    if (!AREAS[entry.name]) throw new Error('Bundle ' + entry.name + ' has no static area; add it to AREAS in tools/js-bundle/build.cjs');
    seen.add(entry.name);
    entry.output = 'web/static/' + AREAS[entry.name] + '/js/' + entry.name + '.js';
  }
  return found;
}

async function build(entry) {
  const result = await esbuild.build({
    entryPoints: [path.join(root, entry.source, 'index.js')],
    absWorkingDir: root,
    bundle: true, format: 'iife', platform: 'browser', target: 'es2020',
    // The Go asset pipeline minifies at startup; unminified output keeps diffs and stack traces readable.
    minify: false, charset: 'utf8', legalComments: 'inline', write: false, metafile: true,
    // ES modules are strict; keep the bundle strict too, as the hand-written files were.
    banner: {js: '// Generated by tools/js-bundle/build.cjs from ' + entry.source + '. Do not edit.\n\'use strict\';'}
  });
  return {contents: result.outputFiles[0].contents, inputs: Object.keys(result.metafile.inputs)};
}

async function main() {
  const check = process.argv.includes('--check');
  const stale = [];
  // A component or page module bundled twice would ship twice and keep two copies of its state;
  // only the stateless helpers in lib/ may be shared between bundles.
  const owners = new Map();
  for (const entry of entries()) {
    const {contents, inputs} = await build(entry);
    for (const input of inputs) {
      if (input.startsWith(sourceRoot + '/lib/')) continue;
      if (owners.has(input)) throw new Error(input + ' is bundled into both ' + owners.get(input) + ' and ' + entry.name);
      owners.set(input, entry.name);
    }
    const target = path.join(root, entry.output);
    if (check) {
      if (!fs.existsSync(target) || !fs.readFileSync(target).equals(Buffer.from(contents))) stale.push(entry.output);
    } else {
      fs.mkdirSync(path.dirname(target), {recursive: true});
      fs.writeFileSync(target, contents);
    }
  }
  if (stale.length) throw new Error(stale.join(', ') + ' needs regeneration; run node tools/js-bundle/build.cjs');
  console.log(check ? 'Generated JavaScript bundles are current.' : 'Generated JavaScript bundles.');
}

main().catch(err => {console.error(err.message || err); process.exitCode = 1;});
