// The public host serves only shared and public assets, and signed-out pages only shared and auth ones;
// a template that referenced anything else would break for those visitors.
test('templates only reference static areas their visitors can fetch',()=>{
 const templates=[];(function visit(dir){for(const file of fs.readdirSync(dir,{withFileTypes:true})) {const name=dir+'/'+file.name;if(file.isDirectory()) visit(name);else if(name.endsWith('.html')) templates.push(name.slice('web/templates/'.length));}})('web/templates');
 const side=name=>/^(public_dashboard\.html|layout\/public_base\.html|partials\/public\/)/.test(name) ? 'public' : /^(login\.html|setup\.html|layout\/auth_base\.html)$/.test(name) ? 'auth' : name.startsWith('partials/common/') ? 'common' : 'admin';
 const allowed={public:['shared','public'],auth:['shared','auth'],admin:['shared','admin'],common:['shared']};
 for(const name of templates) {
  const html=fs.readFileSync('web/templates/'+name,'utf8');
  assert.doesNotMatch(html,/bootstrap\.js/,name);
  const refs=[...html.matchAll(/\{\{asset "([^"]+)"\}\}|\{\{\.StaticPath\}\}\/([a-z]+\/[^"{]+)/g)].map(m=>m[1]||m[2]);
  for(const ref of refs) assert.ok(allowed[side(name)].includes(ref.split('/')[0]),name+' references '+ref+', which its '+side(name)+' visitors cannot fetch');
 }
});
